/**
 * Writes which code points each of Excalidraw's font files covers, so an
 * exported SVG embeds only the files its text needs
 * (src/features/mcp/export/font-files.ts). Re-run after an
 * @excalidraw/excalidraw upgrade:
 *
 *   pnpm tsx scripts/export-fonts.ts
 */

import { readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import * as fontkit from "fontkit"

const fontsDir = "node_modules/@excalidraw/excalidraw/dist/prod/fonts"
const outFile = "src/features/mcp/export/font-files.ts"

// Font folder → the family name text elements use. Assistant is UI-only.
const FAMILIES: Record<string, string> = {
  Excalifont: "Excalifont",
  Virgil: "Virgil",
  Nunito: "Nunito",
  Lilita: "Lilita One",
  ComicShanns: "Comic Shanns",
  Cascadia: "Cascadia",
  Liberation: "Liberation Sans",
  Xiaolai: "Xiaolai",
}

/** Sorted code points as "start-end" runs in base 36, comma-separated. */
function encodeRanges(codePoints: number[]) {
  const runs: string[] = []
  let start = codePoints[0]
  let end = start
  const flush = () =>
    runs.push(
      start === end
        ? start.toString(36)
        : `${start.toString(36)}-${end.toString(36)}`,
    )
  for (const codePoint of codePoints.slice(1)) {
    if (codePoint === end + 1) {
      end = codePoint
      continue
    }
    flush()
    start = end = codePoint
  }
  flush()
  return runs.join(",")
}

const lines: string[] = []
let count = 0
for (const [folder, family] of Object.entries(FAMILIES)) {
  const files = readdirSync(join(fontsDir, folder)).sort()
  lines.push(`  ${JSON.stringify(family)}: [`)
  for (const file of files) {
    const font = fontkit.openSync(join(fontsDir, folder, file)) as fontkit.Font
    const codePoints = font.characterSet
      .filter((codePoint) => codePoint >= 32 && codePoint !== 0xffff)
      .sort((a, b) => a - b)
    if (codePoints.length === 0) continue
    lines.push(
      `    [${JSON.stringify(`${folder}/${file}`)}, ${JSON.stringify(encodeRanges(codePoints))}],`,
    )
    count++
  }
  lines.push("  ],")
}

writeFileSync(
  outFile,
  `// Generated by scripts/export-fonts.ts. Do not edit.
// Per family: [font file under Excalidraw's fonts/, the code points it covers
// as base-36 "start-end" runs].
export const FONT_FILES: Record<string, [file: string, ranges: string][]> = {
${lines.join("\n")}
}
`,
)
console.log(`Wrote ${count} font files to ${outFile}`)
