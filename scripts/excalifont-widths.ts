/**
 * Writes the Excalifont advance widths the server measures text with when it
 * builds a scene (src/features/mcp/scene/excalifont-widths.ts). Re-run after
 * an @excalidraw/excalidraw upgrade:
 *
 *   pnpm tsx scripts/excalifont-widths.ts
 */

import { readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import * as fontkit from "fontkit"

const fontsDir =
  "node_modules/@excalidraw/excalidraw/dist/prod/fonts/Excalifont"
const outFile = "src/features/mcp/scene/excalifont-widths.ts"

// The font ships as unicode-range subsets; together they cover every glyph.
const widths = new Map<number, number>()
for (const file of readdirSync(fontsDir)) {
  const font = fontkit.openSync(join(fontsDir, file)) as fontkit.Font
  for (const codePoint of font.characterSet) {
    if (codePoint < 32 || codePoint === 0xffff) continue
    const glyph = font.glyphForCodePoint(codePoint)
    widths.set(
      codePoint,
      Math.round((glyph.advanceWidth / font.unitsPerEm) * 1000),
    )
  }
}

const entries = [...widths].sort(([a], [b]) => a - b)
const body = entries
  .map(([codePoint, width]) => `${codePoint}:${width}`)
  .join(",")

writeFileSync(
  outFile,
  `// Generated by scripts/excalifont-widths.ts. Do not edit.
// Excalifont advance widths in thousandths of an em, keyed by code point,
// encoded "codePoint:width,..." to keep the file small.
export const EXCALIFONT_WIDTHS = "${body}"
`,
)
console.log(`Wrote ${entries.length} widths to ${outFile}`)
